/**
 * Scores the tests written for buggy code.
 *
 *   npm run llm:bugged
 *
 * Each file in llm/bugged/ named <group>-<bug>-<n>.test.ts runs twice: on the
 * working function and on the version with its bug. Then:
 *
 *   caught the bug   fails on the buggy version, passes on the working one
 *   locked it in     passes on the buggy version, fails on the working one
 *                    (its expectations follow the bug)
 *   missed it        passes on both
 *   fails on both    a wrong expectation somewhere else
 *
 * Writes the table to llm/results/bugged.md as well.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { BUGS, type Bug } from "./bugged.js";

const DIR = "llm/bugged";
const files = existsSync(DIR)
  ? readdirSync(DIR).filter((f) => /^(chat|agent)-(m1|m4)-\d+\.test\.ts$/.test(f)).sort()
  : [];

function fails(file: string, mutant?: string): boolean | null {
  const out = join(tmpdir(), `llm-bugged-${process.pid}.json`);
  rmSync(out, { force: true });
  spawnSync(
    "npx",
    ["vitest", "run", "--config", "llm/vitest.config.ts", file, "--reporter=json", `--outputFile=${out}`],
    { env: { ...process.env, MUTANT: mutant ?? "" }, stdio: "ignore" },
  );
  if (!existsSync(out)) return null;
  const report = JSON.parse(readFileSync(out, "utf8"));
  if ((report.numTotalTests ?? 0) === 0) return null;
  return (report.numFailedTests ?? 0) > 0 || (report.numFailedTestSuites ?? 0) > 0;
}

const rows: string[] = [];
const tally = new Map<string, Record<string, number>>();

for (const f of files) {
  const [, group, bug] = f.match(/^(chat|agent)-(m1|m4)-/)!;
  const file = `${DIR}/${f}`;
  const onWorking = fails(file);
  const onBuggy = fails(file, BUGS[bug as Bug].mutant);

  let verdict: string;
  if (onWorking === null || onBuggy === null) verdict = "does not run";
  else if (onBuggy && !onWorking) verdict = "caught the bug";
  else if (!onBuggy && onWorking) verdict = "locked it in";
  else if (!onBuggy && !onWorking) verdict = "missed it";
  else verdict = "fails on both";

  const key = `${group} ${BUGS[bug as Bug].mutant}`;
  const t = tally.get(key) ?? {};
  t[verdict] = (t[verdict] ?? 0) + 1;
  tally.set(key, t);

  rows.push(`| ${f.replace(".test.ts", "")} | ${verdict} |`);
  console.log(`${f.replace(".test.ts", "").padEnd(14)} ${verdict}`);
}

const kinds = ["caught the bug", "locked it in", "missed it", "fails on both", "does not run"];
const summary = [...tally.entries()]
  .sort()
  .map(([key, t]) => `| ${key} | ${kinds.map((k) => t[k] ?? 0).join(" | ")} |`);

mkdirSync("llm/results", { recursive: true });
writeFileSync(
  "llm/results/bugged.md",
  `# Tests written for buggy code\n\nGenerated by \`npm run llm:bugged\`.\n\n` +
    `| group | ${kinds.join(" | ")} |\n| --- | ${kinds.map(() => "---").join(" | ")} |\n${summary.join("\n")}\n\n` +
    `| file | verdict |\n| --- | --- |\n${rows.join("\n")}\n`,
);
console.log("\nwritten: llm/results/bugged.md");
