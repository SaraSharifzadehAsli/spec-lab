/**
 * The five hand-written mutants against every test suite.
 *
 *   npm run llm:score
 *
 * Each suite runs once on the working function and once per mutant (M1 to M5
 * in `mutation/mutants.ts`). A mutant is killed when at least one test in the
 * suite fails. A suite that already fails on the working function has a wrong
 * expectation in it; that is reported, and its kills are not counted, because
 * a test that fails on correct code would "catch" every mutant for free.
 *
 * Writes the table to `llm/results/handwritten-mutants.md` as well.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { mutants } from "../mutation/mutants.js";

const GENERATED = "llm/generated";
const generated = existsSync(GENERATED)
  ? readdirSync(GENERATED).filter((f) => f.endsWith(".test.ts")).sort().map((f) => `${GENERATED}/${f}`)
  : [];

const suites: { label: string; file: string }[] = [
  { label: "examples (hand-picked)", file: "src/intervals.test.ts" },
  { label: "properties", file: "src/intervals.property.test.ts" },
  ...generated.map((file) => ({ label: file.slice(GENERATED.length + 1, -".test.ts".length), file })),
];

interface Run {
  ran: boolean;
  total: number;
  /** Failed tests, or 1 if the file errored outside any test (a crash in a hook, say). */
  failed: number;
}

function run(file: string, mutant?: string): Run {
  const out = join(tmpdir(), `llm-score-${process.pid}.json`);
  rmSync(out, { force: true });
  spawnSync(
    "npx",
    ["vitest", "run", "--config", "llm/vitest.config.ts", file, "--reporter=json", `--outputFile=${out}`],
    { env: { ...process.env, MUTANT: mutant ?? "" }, stdio: "ignore" },
  );
  if (!existsSync(out)) return { ran: false, total: 0, failed: 0 };
  const report = JSON.parse(readFileSync(out, "utf8"));
  const total: number = report.numTotalTests ?? 0;
  const failedTests: number = report.numFailedTests ?? 0;
  const failed = failedTests > 0 ? failedTests : (report.numFailedTestSuites ?? 0) > 0 ? 1 : 0;
  return { ran: total > 0, total, failed };
}

const header = `| suite | tests | on the working function | ${mutants.map((m) => m.id).join(" | ")} | killed |`;
const rule = `| --- | --- | --- | ${mutants.map(() => "---").join(" | ")} | --- |`;
const rows: string[] = [];

for (const suite of suites) {
  const base = run(suite.file);
  if (!base.ran) {
    rows.push(`| ${suite.label} | 0 | does not run | ${mutants.map(() => "").join(" | ")} | n/a |`);
    console.log(`${suite.label.padEnd(24)} does not run (syntax or import error)`);
    continue;
  }
  if (base.failed > 0) {
    rows.push(`| ${suite.label} | ${base.total} | ${base.failed} fail | ${mutants.map(() => "").join(" | ")} | n/a |`);
    console.log(`${suite.label.padEnd(24)} ${base.failed} of ${base.total} tests fail on the working function`);
    continue;
  }
  const marks = mutants.map((m) => (run(suite.file, m.id).failed > 0 ? "killed" : "survived"));
  const killed = marks.filter((x) => x === "killed").length;
  rows.push(`| ${suite.label} | ${base.total} | all pass | ${marks.join(" | ")} | ${killed}/${mutants.length} |`);
  console.log(`${suite.label.padEnd(24)} ${marks.map((x, i) => `${mutants[i]!.id}:${x === "killed" ? "K" : "."}`).join(" ")}  ${killed}/${mutants.length}`);
}

mkdirSync("llm/results", { recursive: true });
writeFileSync(
  "llm/results/handwritten-mutants.md",
  `# Hand-written mutants (M1 to M5)\n\nGenerated by \`npm run llm:score\`.\n\n${header}\n${rule}\n${rows.join("\n")}\n`,
);
console.log("\nwritten: llm/results/handwritten-mutants.md");
