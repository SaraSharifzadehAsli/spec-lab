/**
 * Stryker's automatic mutants against every test suite.
 *
 *   npm run llm:stryker
 *
 * Runs Stryker once per suite. Score = (killed + timeout) / (killed + timeout
 * + survived + no coverage). A suite with a test that fails on the working
 * function cannot be scored: Stryker stops before mutating.
 *
 * Writes the table to `llm/results/stryker.md` as well.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const GENERATED = "llm/generated";
const REPORT = "reports/mutation/mutation.json";
const generated = existsSync(GENERATED)
  ? readdirSync(GENERATED).filter((f) => f.endsWith(".test.ts")).sort().map((f) => `${GENERATED}/${f}`)
  : [];

const suites: { label: string; file: string }[] = [
  { label: "examples (hand-picked)", file: "src/intervals.test.ts" },
  { label: "properties", file: "src/intervals.property.test.ts" },
  ...generated.map((file) => ({ label: file.slice(GENERATED.length + 1, -".test.ts".length), file })),
];

const rows: string[] = [];

for (const suite of suites) {
  rmSync(REPORT, { force: true });
  spawnSync("npx", ["stryker", "run"], { env: { ...process.env, SUITE: suite.file }, stdio: "ignore" });

  if (!existsSync(REPORT)) {
    rows.push(`| ${suite.label} | | | | n/a: fails or does not run on the working function |`);
    console.log(`${suite.label.padEnd(24)} could not be scored (fails or does not run on the working function)`);
    continue;
  }

  const report = JSON.parse(readFileSync(REPORT, "utf8"));
  const count: Record<string, number> = {};
  for (const file of Object.values<any>(report.files)) {
    for (const m of file.mutants) count[m.status] = (count[m.status] ?? 0) + 1;
  }
  const detected = (count.Killed ?? 0) + (count.Timeout ?? 0);
  const undetected = (count.Survived ?? 0) + (count.NoCoverage ?? 0);
  const total = detected + undetected;
  const pct = total ? Math.round((detected / total) * 100) : 0;

  rows.push(`| ${suite.label} | ${total} | ${detected} | ${undetected} | ${pct}% |`);
  console.log(`${suite.label.padEnd(24)} ${detected}/${total} detected  (${pct}%)`);
}

mkdirSync("llm/results", { recursive: true });
writeFileSync(
  "llm/results/stryker.md",
  `# Stryker mutants\n\nGenerated by \`npm run llm:stryker\`. Only \`mergeIntervals\` is mutated.\n\n| suite | mutants | detected | survived | score |\n| --- | --- | --- | --- | --- |\n${rows.join("\n")}\n`,
);
console.log("\nwritten: llm/results/stryker.md");
